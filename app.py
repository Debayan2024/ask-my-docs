# ---Lifespan need for the easy startup and exit of the code/API

@asynccontextmanager
async def lifespan(app: FastAPI):
    logger.info("Application Initializing ....")

   # load the configurations and other modules required to successfully run FastAPI
    try:
        config = ConfigParser().config_loader()
        if not config:
            logger.error(f"No config found")
            app.state.rag_query_handler = None
        else:
            app.state.rag_query_handler = RAGQueryHandler(config)
            logger.info("✅ RAGQueryHandler initialized successfully and attached to app.state.")
    except Exception as e:
        logger.error(f"❌ Critical error during RAG component initialization on startup: {e}", exc_info=True)
        app.state.rag_query_handler = None # Ensure it's None on failure

    yield  # This is where the application runs --> Control will be passed to the FastAPI to receive requests.
    # Code here runs on shutdown (optional)
    logger.info("Application shutdown: Cleaning up RAG components (if any)...")

# initialize FASTAPI
app = FastAPI(title="RAG Based Knowledge Assistant",
            description="Application to get information from a specific knowledge base.",
            version="0.1.0",
            lifespan=lifespan)

# --- Pydantic Models for Request and Response ---
# Helps in data validation, serialization/deserialization, and API documentation.
class QueryRequest(BaseModel):
    """
    When a request comes into our /query endpoint, FastAPI uses the QueryRequest model
    to automatically validate the incoming JSON payload.
    Type Checking: It ensures that query is a string and top_k (if provided) is an integer.
    If a client sends a query that's an integer or top_k that's a string, FastAPI will 
    automatically return a 422 "Unprocessable Entity" error with a descriptive message 
    before our endpoint logic even runs.
    """
    query: str
    top_k: int = 3

class SourceDocument(BaseModel):
    """
    """
    source: str
    page_content_preview: str

class QueryResponse(BaseModel):
    """
    When our /query endpoint is ready to send a response, FastAPI uses the QueryResponse model
    (and SourceDocument within it) to serialize our Python dictionary/objects into a valid JSON response.
    Structure Enforcement: It ensures the outgoing JSON matches the defined structure. If our endpoint logic 
    accidentally tries to return data that doesn't fit the QueryResponse model (e.g., answer is an integer instead 
    of a string, or source_documents is not a list of the correct objects), Pydantic will raise an error during 
    serialization (which FastAPI usually catches and reports).
    """
    query: str
    answer: str
    source_documents: List[SourceDocument]

@app.post("/query", response_model=QueryResponse, tags=["RAG QUERY"])
async def ask_query(request: QueryRequest) -> QueryResponse:
    """
    Accepts a user query and returns an answer generated by the RAG system.
    """
    rag_query_handler = app.state.rag_query_handler
    if not rag_query_handler:
        logger.error("RAGQueryHandler not initialized. Cannot process query.")
        raise HTTPException(status_code=503, detail="RAG service not available. Initialization failed or in progress.")
    

    if not request.query or not request.query.strip():
        raise HTTPException(status_code=400, detail="Query cannot be empty.")

    logger.info(f"Received query: '{request.query}', top_k: {request.top_k}")

    try:
        result = rag_query_handler.answer_query(request.query)

        return QueryResponse(
            query=result["query"],
            answer=result["answer"],
            source_documents=[SourceDocument(**doc) for doc in result.get("source_documents", [])]
        )
    except Exception as e:
        logger.error(f"Error processing query '{request.query}': {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"An error occurred while processing your query: {str(e)}")


@app.get("/health", tags=["System"])
async def health_check():
    """
    Simple health check endpoint.
    """
    rag_handler_ready = hasattr(app.state, 'rag_query_handler') and app.state.rag_query_handler is not None
    return {"status": "ok", "rag_handler_initialized": rag_handler_ready}
